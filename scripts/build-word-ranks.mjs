#!/usr/bin/env node
// Writes src/helpers/englishWordRanks.mjs: the commonest English words in
// order, which the topic tracker reads to prefer distinctive words over common
// ones when it names a topic (`conversationTopics.mjs`).
//
//   node scripts/build-word-ranks.mjs 1grams_english.csv [--limit 10000]
//
// The source is the English 1-gram list of github.com/orgtre/google-books-ngram-frequency
// (ngrams/1grams_english.csv): the Google Books Ngram corpus (version 3, books
// from 2010 to 2019), cleaned and counted by that repository, which licenses
// its content under Creative Commons Attribution 3.0 Unported. Download it by
// hand; this script never fetches anything.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { limit: { type: "string", default: "10000" } },
});
if (!positionals[0]) {
  console.error("usage: node scripts/build-word-ranks.mjs 1grams_english.csv [--limit N]");
  process.exit(2);
}

const limit = Number(values.limit);
const words = [];
const seen = new Set();
for (const line of fs.readFileSync(positionals[0], "utf8").split(/\r?\n/).slice(1)) {
  // Case is folded: "I" and "i", "May" and "may" are one word to the tracker.
  const word = line.split(",")[0]?.toLowerCase();
  if (!word || !/^[a-z]+$/.test(word) || seen.has(word)) continue;
  seen.add(word);
  words.push(word);
  if (words.length >= limit) break;
}

const out = `// Generated by scripts/build-word-ranks.mjs. Do not edit by hand.
//
// The ${words.length} commonest English words, commonest first. The topic tracker
// reads a word's rank as how common it is in English, so that a topic is named
// after its distinctive words rather than its common ones.
//
// Source: the English 1-gram list of github.com/orgtre/google-books-ngram-frequency,
// counted from the Google Books Ngram corpus (version 3, books from 2010 to
// 2019). Licensed under Creative Commons Attribution 3.0 Unported
// (https://creativecommons.org/licenses/by/3.0/). Changed: case folded, words
// with characters other than a to z left out.

export const ENGLISH_WORD_RANKS =
  "${words.join(" ")}";
`;
const target = path.join(ROOT, "src/helpers/englishWordRanks.mjs");
fs.writeFileSync(target, out);
console.log(`${path.relative(ROOT, target)}: ${words.length} words, ${out.length} bytes`);
